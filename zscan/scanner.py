"""Ties the analysers together for one file or a directory tree."""
from __future__ import annotations

import multiprocessing
import os
from concurrent.futures import FIRST_COMPLETED, ProcessPoolExecutor, wait
from concurrent.futures.process import BrokenProcessPool
from pathlib import Path
from typing import Iterable, Iterator

from . import analysis
from .analysis import PACKING, FileReport, Finding
from .archives import ARCHIVE_TYPES, UNSUPPORTED_ARCHIVES, ZIP_BOMB, Budget, Limits, iter_members
from .config import cache_dir
from .elf import elf_findings
from .ml.model import MODEL_LABELS, MlScorer
from .yara_engine import YaraEngine, community_dir

MAX_BYTES_DEFAULT = 64 * 1024 * 1024
BINARY_TYPES = {"pe", "dos", "elf", "macho", "macho-fat"}
# File types worth spending a slow VirusTotal lookup on even when they look clean.
VT_TYPES = BINARY_TYPES | {"script", "ole", "pdf"} | ARCHIVE_TYPES | set(UNSUPPORTED_ARCHIVES)
ARCHIVE_SEP = "!"   # shown as outer.zip!inner/file.exe
CONTAINER_TYPES = {"zip", "gzip", "bzip2", "xz", "tar"}   # members get their own scan once unpacked

# Windows marks files whose contents live elsewhere, such as OneDrive "online-only" files.
# Reading one makes Windows download it, so a whole-drive scan could pull an entire cloud
# drive onto the disk. These are reported as skipped instead (they are not on this machine).
_FILE_ATTRIBUTE_OFFLINE = 0x1000
_FILE_ATTRIBUTE_RECALL_ON_OPEN = 0x40000
_FILE_ATTRIBUTE_RECALL_ON_DATA_ACCESS = 0x400000
_NOT_LOCAL = _FILE_ATTRIBUTE_OFFLINE | _FILE_ATTRIBUTE_RECALL_ON_OPEN | _FILE_ATTRIBUTE_RECALL_ON_DATA_ACCESS
CLOUD_ONLY = "cloud-only (not downloaded)"
OWN_FILE = "ZScan's own file (its rules, code or reports)"
# Files from ZScan's own history that ZScan would flag: older rule files, source that lists what it
# looks for, test samples. Generated by tools/own_history.py, so that copies of older versions (in
# pip's cache, in old downloads or checkouts) are recognised as well as the running one.
PACKAGE_DIR = Path(__file__).parent
OWN_HISTORY = PACKAGE_DIR / "own-history.sha256"
# Kinds of file ZScan's package folder holds. Anything else found there is scanned like any other file.
_PACKAGE_SUFFIXES = {".py", ".pyc", ".yar", ".sha256"}
_IO_REPARSE_TAG_MOUNT_POINT = 0xA0000003     # directory junctions and mounted volumes


def not_local(st: os.stat_result) -> bool:
    """True for a file whose bytes are not on this machine (Windows cloud placeholders)."""
    return bool(getattr(st, "st_file_attributes", 0) & _NOT_LOCAL)


def is_junction(path: str) -> bool:
    """Windows directory junction (or a volume mounted on a folder). Always False elsewhere."""
    check = getattr(os.path, "isjunction", None)     # Python 3.12+
    if check is not None:
        return check(path)
    try:
        return getattr(os.lstat(path), "st_reparse_tag", 0) == _IO_REPARSE_TAG_MOUNT_POINT
    except OSError:
        return False


def reports_registry() -> Path:
    """Where ZScan notes the SHA-256 of every report it wrote with -o (reports quote findings)."""
    return cache_dir() / "reports.sha256"


def _hash_file(path) -> str:
    import hashlib
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def _read_hash_list(path: Path) -> set:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return set()
    return {ln.split()[0].lower() for ln in lines if ln.strip() and not ln.startswith("#")}


def remember_report(path) -> None:
    """Note a report ZScan just wrote, so later scans know it as ZScan's own file."""
    try:
        digest = _hash_file(path)
        reg = reports_registry()
        reg.parent.mkdir(parents=True, exist_ok=True)
        with open(reg, "a", encoding="utf-8") as fh:
            fh.write(f"{digest}  {Path(path).name}\n")
    except OSError:
        pass        # an unwritable cache folder only means the report gets flagged next time


def own_file_hashes(engine: YaraEngine | None) -> frozenset:
    """SHA-256 of ZScan's own files: its code (all of the package), the YARA rule files it loaded,
    the downloaded community rules, flagged files from ZScan's own history (OWN_HISTORY) and the
    reports it wrote. Rule files are full of the very strings they look for, and reports quote
    what they found, so scanning them only produces alarms about ZScan itself. Matching by exact
    content (not by folder) also catches copies, for example inside a pip-cached wheel, and
    leaves no folder where something else could hide unscanned."""
    import sys
    files = set()
    for name, mod in list(sys.modules.items()):
        if name == __package__ or name.startswith(__package__ + "."):
            files.update(getattr(mod, attr, None) for attr in ("__file__", "__cached__"))
    # The rest of the package as well: modules this run did not import, and bytecode compiled
    # by other Python versions.
    try:
        files.update(str(f) for f in PACKAGE_DIR.rglob("*") if f.suffix in _PACKAGE_SUFFIXES)
    except OSError:
        pass
    if engine is not None:
        files.update(getattr(engine, "rule_files", []))
    files.update(str(community_dir() / f"yara-forge{ext}") for ext in (".yar", ".yarc", ".json"))
    out = _read_hash_list(OWN_HISTORY) | _read_hash_list(reports_registry())
    for f in files:
        try:
            out.add(_hash_file(f))
        except (OSError, TypeError):
            pass
    return frozenset(out)


class Scanner:
    """Two phases, so the slow part can run in worker processes:

    analyze_*  looks at the bytes only (hashes, YARA, heuristics, unpacking).
    finalize   runs in the main process: hash lookups, then each archive takes
               the verdict of its worst member.
    scan_file  does both.
    """

    def __init__(self, yara_engine: YaraEngine | None = None, max_bytes: int = MAX_BYTES_DEFAULT,
                 unpack: bool = True, limits: Limits | None = None,
                 hash_list=None, online=None, ml: MlScorer | None = None, own_hashes=None):
        self.yara = yara_engine or YaraEngine()
        self.max_bytes = max_bytes
        self.unpack = unpack
        self.limits = limits or Limits(max_member_bytes=max_bytes)
        self.hash_list = hash_list   # intel.HashList or None
        self.online = online         # intel.OnlineIntel or None
        self.ml = ml                 # ml.model.MlScorer or None (opt-in --ml)
        self.own_hashes = own_file_hashes(self.yara) if own_hashes is None else frozenset(own_hashes)

    # ------------------------------------------------------------ phase 1: analyse

    def analyze_file(self, path: Path) -> FileReport:
        rep = FileReport(path=str(path))
        try:
            st = path.stat()        # reads attributes only; never downloads a cloud file
            rep.size = st.st_size
            if not_local(st):
                rep.skipped = CLOUD_ONLY
                return rep
            if rep.size > self.max_bytes:
                rep.skipped = f"larger than {self.max_bytes // (1024 * 1024)} MiB"
                return rep
            data = path.read_bytes()
        except OSError as e:
            rep.error = f"cannot read: {e.strerror or e}"
            return rep
        return self.analyze_bytes(data, str(path), Budget(self.limits), depth=0)

    def analyze_bytes(self, data: bytes, display: str, budget: Budget, depth: int) -> FileReport:
        rep = FileReport(path=display, size=len(data))
        rep.hashes = analysis.hashes(data)
        if rep.hashes["sha256"] in self.own_hashes:
            rep.skipped = OWN_FILE
            return rep
        rep.entropy = round(analysis.shannon_entropy(data), 3)
        rep.file_type = analysis.detect_type(data)

        f = rep.findings
        found, notes = self.yara.scan(data)
        f += found
        rep.unscanned += notes
        # Text patterns only make sense on text-like bytes. Short ones match random data by
        # chance, so skip compressed or encrypted content, and containers whose members
        # are scanned on their own once unpacked.
        skip_strings = (rep.size > 4096 and rep.entropy > 7.2) or (self.unpack and rep.file_type in CONTAINER_TYPES)
        strings = [] if skip_strings else analysis.string_findings(data)
        if rep.file_type in BINARY_TYPES:
            # Compiled programs embed lots of harmless text (help strings, docs,
            # e.g. Go tools mention Invoke-Expression), so string hits count less.
            for s in strings:
                s.severity = max(1, s.severity - 1)
        f += strings
        if rep.file_type == "pe":
            f += analysis.pe_findings(data)
        elif rep.file_type == "elf":
            f += elf_findings(data)
        # Whole-file entropy matters mostly for executables; compressed formats
        # (zip, gzip, pdf streams) are naturally near 8.0.
        if rep.entropy > 7.5 and rep.size > 4096 and rep.file_type in ("pe", "elf", "data", "script"):
            f.append(Finding("entropy", "Very high file entropy", 2,
                             f"{rep.entropy} bits/byte (encrypted or packed content?)", group=PACKING))

        if self.ml is not None:
            self._ml_check(rep, data)

        if self.unpack:
            if rep.file_type in ARCHIVE_TYPES:
                self._unpack(rep, data, budget, depth)
            elif rep.file_type in UNSUPPORTED_ARCHIVES:
                rep.unscanned.append(f"{UNSUPPORTED_ARCHIVES[rep.file_type]} archive: "
                                     "contents not scanned (format not supported)")
        return rep

    def _ml_check(self, rep: FileReport, data: bytes) -> None:
        """Score ELF, PDF and APK files with the EMBER2024 model for that type."""
        kind = self.ml.kind_for(rep.file_type, data)
        if kind is None:
            return
        label = MODEL_LABELS[kind]
        if not self.ml.has_model(kind):
            rep.unscanned.append(f"ML check not run: no {label} model installed (zscan --update-ml)")
            return
        try:
            result = self.ml.score(kind, data)
        except Exception as e:  # noqa: BLE001 - the ML step must never break a scan
            rep.unscanned.append(f"ML check failed on this {label} file: {type(e).__name__}")
            return
        if result is None:
            rep.unscanned.append(f"ML check not run: {label} file too small to judge")
            return
        rep.ml = {"model": result.model, "score": round(result.score, 4)}
        sev = self.ml.severity(result.score)
        title = "ML model: resembles known malware" if sev > 1 else f"ML model score {result.score:.3f}"
        rep.findings.append(Finding("ml", title, sev, f"score {result.score:.3f}, EMBER2024 {label} model"))

    def _unpack(self, rep: FileReport, data: bytes, budget: Budget, depth: int) -> None:
        if depth >= self.limits.max_depth:
            rep.findings.append(Finding("archive", "Archive nested too deep, not unpacked", 2,
                                        f"more than {self.limits.max_depth} levels"))
            rep.unscanned.append(f"contents not scanned: nested more than {self.limits.max_depth} levels deep")
            return
        encrypted, skipped = [], []
        for m in iter_members(data, rep.file_type, budget):
            label = f"{m.name}: {m.note}" if m.name else (m.note or "")
            if m.encrypted:
                encrypted.append(m.name)
            elif m.bomb:
                rep.findings.append(Finding("archive", "Possible zip bomb", m.bomb, label, group=ZIP_BOMB))
                skipped.append(label)
            elif m.data is None:
                skipped.append(label)
            else:
                rep.children.append(
                    self.analyze_bytes(m.data, f"{rep.path}{ARCHIVE_SEP}{m.name}", budget, depth + 1))
        if encrypted:
            # Password-protected archives are a classic way to slip malware past
            # mail gateways, since nobody can look inside without the password.
            rep.findings.append(Finding("archive", "Password-protected archive members", 3,
                                        f"{len(encrypted)} encrypted, e.g. {encrypted[0]}"))
            rep.unscanned.append(f"{len(encrypted)} password-protected member(s) could not be opened")
        rep.unscanned += skipped[:10]
        if len(skipped) > 10:
            rep.unscanned.append(f"... and {len(skipped) - 10} more archive members not scanned")

    # ------------------------------------------------------------ phase 2: finalize

    def finalize(self, rep: FileReport) -> FileReport:
        for child in rep.children:
            self.finalize(child)
        self._intel(rep)
        if rep.children:
            self._roll_up(rep)
        rep.findings.sort(key=lambda x: -x.severity)
        return rep

    def _intel(self, rep: FileReport) -> None:
        sha = rep.hashes.get("sha256")
        if not sha or rep.skipped:      # ZScan's own files carry hashes but were not scanned
            return
        if self.hash_list is not None:
            rep.findings += self.hash_list.lookup(rep.hashes)
        if self.online is not None:
            worth_vt = rep.file_type in VT_TYPES or rep.verdict != "clean"
            rep.findings += self.online.lookup(sha, worth_vt)

    def _roll_up(self, rep: FileReport) -> None:
        """An archive is as bad as the worst thing inside it; point at that file."""
        worst = None
        for c in rep.iter_tree():
            if c is rep or c.verdict in ("clean", "skipped", "error"):
                continue
            # malicious beats suspicious, then higher score; the deepest file wins ties
            key = (c.verdict == "malicious", c.score, c.path.count(ARCHIVE_SEP))
            if worst is None or key > worst[0]:
                worst = (key, c)
        if worst:
            c = worst[1]
            rep.findings.append(Finding("archive", f"Contains {c.verdict} file",
                                        5 if c.verdict == "malicious" else 3, c.path[len(rep.path) + 1:]))

    def scan_file(self, path: Path) -> FileReport:
        return self.finalize(self.analyze_file(path))

    # ------------------------------------------------------------ trees

    def iter_paths(self, target: Path, follow_symlinks: bool = False, on_error=None) -> Iterator[Path]:
        """Files under `target`, in a stable order. `on_error(OSError)` hears about every
        folder that could not be opened (for example no permission), so the caller can
        report it rather than let that part of the tree go missing silently."""
        if target.is_file():
            yield target
            return
        for root, dirs, files in os.walk(target, followlinks=follow_symlinks, onerror=on_error):
            if not follow_symlinks:
                # os.walk leaves symlinked folders alone but enters Windows junctions, which
                # can repeat whole trees or loop (C:\Users\Default User, Application Data).
                dirs[:] = [d for d in dirs if not is_junction(os.path.join(root, d))]
            dirs.sort()
            for name in sorted(files):
                p = Path(root) / name
                if p.is_symlink() and not follow_symlinks:
                    continue
                if p.is_file():
                    yield p

    def scan(self, target: Path) -> Iterator[FileReport]:
        """Yield top-level reports. Archive members hang off .children."""
        for p in self.iter_paths(target):
            yield self.scan_file(p)

    def scan_many(self, paths: Iterable[Path], jobs: int = 1) -> Iterator[FileReport]:
        """Scan files in order. With jobs > 1 the analysis runs in worker processes.

        Hash lookups and archive roll-ups stay in this process, so online
        lookups keep their rate limit and the results are the same as jobs=1.
        """
        if jobs <= 1:
            for p in paths:
                yield self.scan_file(p)
            return
        config = {"rule_paths": getattr(self.yara, "rule_paths", None),
                  "community": getattr(self.yara, "use_community", True),
                  "max_bytes": self.max_bytes, "unpack": self.unpack, "limits": self.limits,
                  "own_hashes": self.own_hashes,
                  "ml": ({"threshold": self.ml.threshold, "directory": str(self.ml.directory)}
                         if self.ml is not None else None)}
        pool = _new_pool(jobs, config)
        in_flight: dict = {}     # future -> (position in the input, path)
        ready: dict = {}         # position -> finished report waiting for its turn
        submitted = next_out = 0
        source = iter(paths)
        exhausted = False
        try:
            while True:
                lost = []        # (position, path) whose worker died, or that never reached one
                # Keep every worker busy. Only unfinished work is capped, so one slow
                # file at the front cannot stall the rest; finished reports are small.
                while not exhausted and not lost and len(in_flight) < jobs * 4:
                    try:
                        path = next(source)
                    except StopIteration:
                        exhausted = True
                        break
                    try:
                        in_flight[pool.submit(_worker_scan, str(path))] = (submitted, path)
                    except BrokenProcessPool:       # a worker died since the last check
                        lost.append((submitted, path))
                    submitted += 1
                if not in_flight and not lost:
                    break
                if not lost:
                    done, _ = wait(set(in_flight), return_when=FIRST_COMPLETED)
                    for future in done:
                        pos, path = in_flight.pop(future)
                        try:
                            ready[pos] = future.result()
                        except BrokenProcessPool:
                            lost.append((pos, path))
                        except Exception as e:  # noqa: BLE001 - e.g. a result that could not be sent back
                            ready[pos] = _failed(path, f"internal error: {type(e).__name__}: {e}")
                if lost:
                    # A worker died, most likely because a native library (YARA, a decompressor)
                    # crashed on some file, and it took the whole pool with it. Keep whatever
                    # finished, then scan every file that was still in flight again, one at a
                    # time, so the file that does it is found and all the others get scanned.
                    pool.shutdown(wait=True, cancel_futures=True)
                    for future, (pos, path) in in_flight.items():
                        if future.done() and not future.cancelled() and future.exception() is None:
                            ready[pos] = future.result()
                        else:
                            lost.append((pos, path))
                    in_flight.clear()
                    for pos, rep in _isolate(sorted(lost), config):
                        ready[pos] = rep
                    pool = _new_pool(jobs, config)
                while next_out in ready:       # hand results out in input order
                    yield self.finalize(ready.pop(next_out))
                    next_out += 1
        finally:
            pool.shutdown(wait=True, cancel_futures=True)   # also runs if the caller stops early (Ctrl-C)


class WorkerCrashed(RuntimeError):
    """Scan workers keep dying even without a file to blame, so the scan cannot go on."""


CRASHED = "a scan worker crashed on this file, so it was not scanned"
# Tests only: a worker exits abruptly on files whose name contains this text ("*" means every
# scan, including the start-up probe). Lets tests imitate a native crash without a real one.
_CRASH_FOR_TESTS = os.environ.get("ZSCAN_TEST_CRASH_ON", "")


def _failed(path, why: str) -> FileReport:
    rep = FileReport(path=str(path))
    rep.error = why
    return rep


def _new_pool(jobs: int, config: dict) -> ProcessPoolExecutor:
    # "spawn" behaves the same on every OS and avoids forking a process that already holds YARA state.
    return ProcessPoolExecutor(max_workers=jobs, mp_context=multiprocessing.get_context("spawn"),
                               initializer=_worker_init, initargs=(config,))


def _isolate(items: list, config: dict) -> Iterator[tuple]:
    """Scan each (position, path) on its own in a one-worker pool, to find the file that kills
    its worker. A file is blamed only if it does so twice in a row (a crash can have other
    causes, such as running out of memory) and a fresh worker then still scans a few harmless
    bytes. If even that fails, the workers themselves are broken, not any file: give up."""
    pool = None

    def attempt(path) -> FileReport | None:
        """The file's report, or None if its worker died."""
        nonlocal pool
        for _ in range(2):      # a pool that died while idle is not this file's doing: replace it
            if pool is None:
                pool = _new_pool(1, config)
            try:
                future = pool.submit(_worker_scan, str(path))
                break
            except BrokenProcessPool:
                pool.shutdown(wait=True, cancel_futures=True)
                pool = None
        else:
            raise WorkerCrashed("scan workers die as soon as they start, so the scan cannot go on")
        try:
            return future.result()
        except BrokenProcessPool:
            pool.shutdown(wait=True, cancel_futures=True)
            pool = None
            return None
        except Exception as e:  # noqa: BLE001
            return _failed(path, f"internal error: {type(e).__name__}: {e}")

    try:
        for pos, path in items:
            rep = attempt(path)
            if rep is None:
                rep = attempt(path)
            if rep is None:
                if not _workers_start(config):
                    raise WorkerCrashed("scan workers crash even on a harmless test input, so the "
                                        "problem is not one file; try --jobs 1")
                rep = _failed(path, CRASHED)
            yield pos, rep
    finally:
        if pool is not None:
            pool.shutdown(wait=True, cancel_futures=True)


def _workers_start(config: dict) -> bool:
    pool = _new_pool(1, config)
    try:
        return pool.submit(_worker_probe).result()
    except BrokenProcessPool:
        return False
    finally:
        pool.shutdown(wait=True, cancel_futures=True)


_WORKER: Scanner | None = None


def _worker_init(config: dict) -> None:
    global _WORKER
    ml = config.get("ml")
    scorer = MlScorer(ml["threshold"], Path(ml["directory"])) if ml else None
    _WORKER = Scanner(YaraEngine(config["rule_paths"], community=config["community"]),
                      max_bytes=config["max_bytes"], unpack=config["unpack"], limits=config["limits"],
                      ml=scorer, own_hashes=config["own_hashes"])


def _worker_probe() -> bool:
    if _CRASH_FOR_TESTS == "*":
        os._exit(70)
    _WORKER.analyze_bytes(b"zscan worker probe", "probe", Budget(_WORKER.limits), 0)
    return True


def _worker_scan(path: str) -> FileReport:
    if _CRASH_FOR_TESTS and (_CRASH_FOR_TESTS == "*" or _CRASH_FOR_TESTS in os.path.basename(path)):
        os._exit(70)
    try:
        return _WORKER.analyze_file(Path(path))
    except Exception as e:  # noqa: BLE001 - one bad file must not stop the whole scan
        return _failed(path, f"internal error: {type(e).__name__}: {e}")

